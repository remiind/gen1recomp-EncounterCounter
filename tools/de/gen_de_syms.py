#!/usr/bin/env python3
"""Write emerald_de.lua / emerald_de_funcs.lua from demap's rows.json.

Keeps the US tables' format (objs, collide, data) and line order; offsets are
the German ones, "~" spans are re-measured in the German ROM, unmapped rows
are left out (a lookup then fails loudly instead of reading the wrong bytes).
"""
import json
import re
import sys

src_dir, out_dir, rows_path, game_de = sys.argv[1:5]
ov = json.load(open(sys.argv[5])) if len(sys.argv) > 5 else {"set": [], "drop": [], "add": []}
ov_set = {(o["name"], o.get("obj")): o for o in ov.get("set", [])}
ov_drop = set(ov.get("drop", []))

rows = json.load(open(rows_path))
de_of = {}       # (func, name, off, obj) -> de offset
en2de = {}       # en offset -> de offset (any mapped row there)
for r in rows:
    if r["de"] is None:
        continue
    de_of[(r["func"], r["name"], r["off"], r["obj"])] = r["de"]
    en2de.setdefault(r["off"], r["de"])

for kind, suffix, is_func in (("data", "", False), ("func", "_funcs", True)):
    src = open(f"{src_dir}/emerald{suffix}.lua", encoding="utf-8").read()
    objs_txt = re.search(r"objs = \[==\[\n(.*?)\]==\]", src, re.S).group(1)
    objs = objs_txt.split("\n")
    data = re.search(r"data = \[==\[\n(.*?)\]==\]", src, re.S)
    out_lines = []
    kept = dropped = 0
    for line in data.group(1).split("\n"):
        m = re.match(r"(\S+) ([0-9a-f]+) (~?)([0-9a-f]+) ?(\d*)$", line)
        if not m:
            if line:
                out_lines.append(line)
            continue
        name, off, span, size, obj = m.groups()
        off, size = int(off, 16), int(size, 16)
        objname = objs[int(obj) - 1] if obj else None
        de = de_of.get((is_func, name, off, objname))
        if name in ov_drop and not is_func:
            dropped += 1
            continue
        o = None if is_func else (ov_set.get((name, objname)) or ov_set.get((name, None)))
        if o:
            de = int(o["de"], 16)
            if "size" in o:
                size = int(o["size"], 16)
                span = ""
        if de is None:
            dropped += 1
            continue
        if span == "~" and size and not o:
            nxt = en2de.get(off + size)
            if nxt is not None and 0 < nxt - de < 0x100000:
                size = nxt - de
        out_lines.append(f"{name} {de:x} {span}{size:x}" + (f" {obj}" if obj else ""))
        kept += 1
    if not is_func:
        # aliases first: Syms keeps the last row per name, so the main row wins
        import os
        al = json.load(open(os.path.join(os.path.dirname(rows_path), "aliases.json"))) if os.path.exists(
            os.path.join(os.path.dirname(rows_path) or ".", "aliases.json")) else []
        alias_lines = []
        seen_al = set()
        for a in al:
            if a["name"] in ov_drop or (a["name"], a["de"]) in seen_al:
                continue
            seen_al.add((a["name"], a["de"]))
            idx = objs.index(a["obj"]) + 1 if a.get("obj") in objs else None
            alias_lines.append(f"{a['name']} {a['de']:x} ~0" + (f" {idx}" if idx else ""))
        out_lines = alias_lines + out_lines
        print(f"  {len(alias_lines)} alias rows")
        for a in ov.get("add", []):
            idx = objs.index(a["obj"]) + 1 if a.get("obj") in objs else None
            out_lines.append(f"{a['name']} {int(a['de'], 16):x} {int(a['size'], 16):x}" + (f" {idx}" if idx else ""))
            kept += 1
    head = src[:data.start(1)]
    head = head.replace('game = "emerald"', f'game = "{game_de}"', 1)
    head = re.sub(r"^-- generated by .*$",
                  "-- generated by demap (US pokeemerald symbols located in the German ROM), addresses only",
                  head, count=1, flags=re.M)
    tail = src[data.end(1):]
    with open(f"{out_dir}/{game_de}{suffix}.lua", "w", encoding="utf-8") as f:
        f.write(head + "\n".join(out_lines) + "\n" + tail)
    print(f"{game_de}{suffix}.lua: {kept} rows, {dropped} left out")
